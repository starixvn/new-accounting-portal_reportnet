using AutoGeneratedReport.Helper;
using AutoGeneratedReport.Models;
using Fanex.Common;
using Microsoft.Extensions.Configuration;

namespace AutoGeneratedReport.Services;

public interface AutoGeneratedHistoryReportService
{
    void ProcessFile(string functionKey, string folder, ICollection<ReportGroup> reportList);

    void ProcessFileForGroupByDay(string functionKey, string folder, ICollection<ReportGroup> reportList);

    void ProcessDirectory(string functionKey, string directory, string parentFunctionKey,
        ICollection<ReportGroup> reportList);
}

public class AutoGeneratedHistoryReportServiceImp(IConfiguration configuration) : AutoGeneratedHistoryReportService
{
    public void ProcessFile(string functionKey, string folder, ICollection<ReportGroup> reportList)
    {
        var latestModifyDate = File.GetLastWriteTime(folder);
        var groupName = latestModifyDate.ToString("MMM - yyyy");

        if (latestModifyDate.Date < DateTime.Today.AddMonths(-12).Date) return;
        var report = new Report
        {
            Name = Path.GetFileName(folder),
            FolderName = folder.Replace(CommonHelper.GetFolder(functionKey, configuration.GetSection("FileServerDirectory").Value!)
                , string.Empty),
            GeneratedDate = latestModifyDate.ToString("yyyy-MM-dd"),
            GeneratedDateFull = latestModifyDate,
            FunctionKey = functionKey
        };

        var group = reportList.Where(s => s.GroupName == groupName).Distinct().FirstOrDefault();

        if (group == null)
        {
            group = new ReportGroup
            {
                GroupName = groupName
            };
            reportList.Add(group);
        }

        group.Reports.Add(report);
        group.Reports = [.. group.Reports.OrderByDescending(s => s.GeneratedDateFull)];
    }

    public void ProcessFileForGroupByDay(string functionKey, string folder, ICollection<ReportGroup> reportList)
    {
        var latestModifyDate = File.GetLastWriteTime(folder);
        var groupName = latestModifyDate.ToString("MMM - yyyy");
        var subGroupName = latestModifyDate.ToString("MMM - dd - yyyy");

        if (latestModifyDate.Date < DateTime.Today.AddMonths(-12).Date) return;
        var report = new Report
        {
            Name = Path.GetFileName(folder),
            FolderName = folder.Replace(CommonHelper.GetFolder(functionKey, configuration.GetSection("FileServerDirectory").Value!)
                , string.Empty),
            GeneratedDate = latestModifyDate.ToString("yyyy-MM-dd"),
            GeneratedDateFull = latestModifyDate,
            FunctionKey = functionKey
        };

        var group = reportList.Where(s => s.GroupName == groupName).Distinct().FirstOrDefault();

        if (group == null)
        {
            group = new ReportGroup
            {
                GroupName = groupName
            };
            reportList.Add(group);
        }

        var subGroup = group.Rows.Where(s => s.GroupName == subGroupName).Distinct().FirstOrDefault();
        if (subGroup == null)
        {
            subGroup = new ReportGroup
            {
                GroupName = subGroupName
            };
            group.Rows.Add(subGroup);
        }

        subGroup.Reports.Add(report);

        subGroup.Reports = subGroup.Reports.OrderByDescending(s => s.GeneratedDateFull).ToList();
        group.Rows = group.Rows.OrderByDescending(s => Converter.To<DateTime>(s.GroupName)).ToList();
    }

    public void ProcessDirectory(string functionKey, string directory, string parentFunctionKey, ICollection<ReportGroup> reportList)
    {
        var files = Directory.GetFiles(directory);
        foreach (var file in files)
        {
            if (parentFunctionKey == "Others")
            {
                ProcessFileForGroupByDay(functionKey, file, reportList);
            }
            else
            {
                ProcessFile(functionKey, file, reportList);
            }
        }

        var subDirectories = Directory.GetDirectories(directory);
        foreach (var subDirectory in subDirectories)
        {
            ProcessDirectory(functionKey, subDirectory, parentFunctionKey, reportList);
        }
    }
}