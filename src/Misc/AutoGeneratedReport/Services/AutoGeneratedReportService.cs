using AutoGeneratedReport.Constants;
using AutoGeneratedReport.Models;
using Fanex.Data.Repository;
using Fanex.NAP.Client.Configuration;
using Fanex.NAP.Client.Helpers.Business;
using Fanex.NAP.Client.Services;
using Nap_Reports.Utilities;

namespace AutoGeneratedReport.Services;

public interface AutoGeneratedReportService
{
    List<ReportFunction> GetAllReportFunctions(int userId);

    void WriteUserLog(string user, string functionKey, string fileName);
}

public class AutoGeneratedReportServiceImp(INapSettings napSettings, IUserService userService, IDynamicRepository dynamicRepository) : AutoGeneratedReportService
{
    public List<ReportFunction> GetAllReportFunctions(int userId)
    {
        var result = new List<ReportFunction>();
        var parentFunctions = userService.GetPermissions(userId, napSettings.SiteId, AccReportFunctionKeys.AutoGeneratedReport, napSettings.Environment)
            .Where(p => p.Policy >= (int)Constant.Policy.Read);
        foreach (var parentFunction in parentFunctions)
        {
            var functions = userService.GetPermissions(userId, napSettings.SiteId, parentFunction.Key, napSettings.Environment)
                .Where(p => p.Policy >= (int)Constant.Policy.Read);
            var reportFunctions = functions.Select(f => new ReportFunction
            {
                FunctionKey = f.Key,
                FunctionName = f.Name,
                ParentFunctionKey = parentFunction.Key,
                Description = f.Description
            });

            result.AddRange(reportFunctions);
        }

        return [.. result.OrderBy(f => f.FunctionName)];
    }

    public void WriteUserLog(string user, string functionKey, string fileName)
    {
        var reportDetail = AutoGeneratedReportConstants.ReportList.TryGetValue(functionKey, out var value) ? value : new ReportDetail();
        var criteria = new DownLoadReportLogCriteria
        {
            FileName = fileName,
            ReportID = reportDetail.ReportId,
            UserEmail = user
        };
        dynamicRepository.Execute(criteria);
    }
}