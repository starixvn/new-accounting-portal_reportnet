namespace AutoGeneratedReport.Services;

using Helper;
using Microsoft.Extensions.Configuration;
using Models;

public interface AutoGeneratedTodayReportService
{
    void ProcessFile(string functionKey, string description, string folder, ICollection<ReportGroup> reportList, string serverFolder);

    void ProcessDirectory(string functionKey, string description, string folder,
        ICollection<ReportGroup> reportList, string serverFolder);

    void DeleteDirectoryAndFile(string zipFile, string folder);
}

public class AutoGeneratedTodayReportServiceImp(IConfiguration configuration) : AutoGeneratedTodayReportService
{
    public void ProcessFile(string functionKey, string description, string folder, ICollection<ReportGroup> reportList, string serverFolder)
    {
        var latestModifyDate = File.GetLastWriteTime(folder);
        if (latestModifyDate.Date != DateTime.Today.Date) return;
        var report = new Report
        {
            Name = Path.GetFileName(folder),
            Description = description,
            FolderName = folder.Replace(CommonHelper.GetFolder(functionKey, serverFolder)
                , string.Empty),
            GeneratedDate = latestModifyDate.ToString("yyyy-MM-dd"),
            GeneratedDateFull = latestModifyDate,
            FunctionKey = functionKey
        };
        var group = reportList.Where(s => s.GroupName == description).Distinct().FirstOrDefault();
        if (group == null)
        {
            group = new ReportGroup
            {
                GroupName = description
            };
            reportList.Add(group);
        }

        group.Reports.Add(report);
        group.Reports = [.. group.Reports.OrderByDescending(s => s.GeneratedDateFull)];
    }

    public void ProcessDirectory(string functionKey, string description, string folder, ICollection<ReportGroup> reportList, string serverFolder)
    {
        var files = Directory.GetFiles(folder);
        foreach (var file in files)
        {
            ProcessFile(functionKey, description, file, reportList, serverFolder);
        }

        var subDirectories = Directory.GetDirectories(folder);
        foreach (var subDirectory in subDirectories)
        {
            ProcessDirectory(functionKey, description, subDirectory, reportList, serverFolder);
        }
    }

    public void DeleteDirectoryAndFile(string zipFile, string folder)
    {
        if (!string.IsNullOrEmpty(zipFile) && File.Exists(zipFile))
        {
            File.Delete(zipFile);
        }
        if (!string.IsNullOrEmpty(folder) && Directory.Exists(folder))
        {
            Directory.Delete(folder, true);
        }
    }
}