namespace AutoGeneratedReport.Helper;

using Constants;
using Models;

public static class CommonHelper
{
    public static string GetFolder(string functionKey, string serverFolder)
    {
        var reportDetail = AutoGeneratedReportConstants.ReportList.TryGetValue(functionKey, out var value) ? value : new ReportDetail();
        var folder = Path.Combine(serverFolder
            .Replace(AutoGeneratedReportConstants.DefaultFolder, reportDetail.ReportFolder));
        if (!string.IsNullOrEmpty(reportDetail.ReportSubFolder))
        {
            folder = Path.Combine(folder, reportDetail.ReportSubFolder);
        }
        return folder;
    }
}