namespace AutoGeneratedReport.Controllers;

using System.IO;
using System.IO.Compression;
using System.Net.Mime;
using Fanex.Common;
using Fanex.NAP.Client;
using Helper;
using Microsoft.AspNetCore.Mvc;
using Microsoft.Extensions.Configuration;
using Models;
using Services;

[Route("api/auto-generated-report")]
[ApiController]
public class AutoGeneratedReportApiController(AutoGeneratedReportService service,
    INapSession napSession,
    AutoGeneratedTodayReportService autoGeneratedTodayReportService,
    AutoGeneratedHistoryReportService autoGeneratedHistoryReportService,
    IConfiguration configuration) : ControllerBase
{
    [Route("reports")]
    public IActionResult GetReports()
    {
        var result = service.GetAllReportFunctions(napSession.UserId);
        return Ok(result);
    }

    [Route("today-reports")]
    public IEnumerable<ReportGroup> GetTodayReports(IEnumerable<ReportFunction> reportsByUser)
    {
        var result = new List<ReportGroup>();
        foreach (var reportItem in reportsByUser)
        {
            var folderList = configuration.GetSection("FileServerDirectory").Value!.Split(",");
            foreach (var folderItem in folderList)
            {
                var folder = CommonHelper.GetFolder(reportItem.FunctionKey, folderItem);

                if (System.IO.File.Exists(folder))
                {
                    autoGeneratedTodayReportService.ProcessFile(reportItem.FunctionKey, reportItem.Description, folder, result, folderItem);
                }
                else
                {
                    if (Directory.Exists(folder))
                    {
                        autoGeneratedTodayReportService.ProcessDirectory(reportItem.FunctionKey, reportItem.Description, folder, result, folderItem);
                    }
                }
            }
            
        }

        return result;
    }

    [Route("history-reports")]
    public IEnumerable<ReportGroup> GetHistoryReports(HistoryReportCriteria criteria)
    {
        var result = new List<ReportGroup>();
        var folderList = configuration.GetSection("FileServerDirectory").Value!.Split(",");
        foreach (var folderItem in folderList)
        {
            var folder = CommonHelper.GetFolder(criteria.FolderName, folderItem);
            if (System.IO.File.Exists(folder))
            {
                if (criteria.ParentFunctionKey == "Others")
                {
                    autoGeneratedHistoryReportService.ProcessFileForGroupByDay(criteria.FolderName, folder, result, folderItem);
                }
                else
                {
                    autoGeneratedHistoryReportService.ProcessFile(criteria.FolderName, folder, result, folderItem);
                }
            }
            else if (Directory.Exists(folder))
            {
                autoGeneratedHistoryReportService.ProcessDirectory(criteria.FolderName, folder, criteria.ParentFunctionKey, result, folderItem);
            }
        }
        
        return result.OrderByDescending(s => Converter.To<DateTime>(s.GroupName));
    }

    [Route("download")]
    public FileStreamResult DownLoadReport(DownloadReportCriteria criteria)
    {
        var fileNames = criteria.FileName.Split('^');
        var isMultiFiles = criteria.IsMultiFiles;
        var data = isMultiFiles ? GetMultiFiles([.. fileNames]) : GetSingleFile(fileNames[0]);
        return data;
    }

    private FileStreamResult GetSingleFile(string file)
    {
        var fileNameAndFunctionKey = file.Split('|')[1];
        var array = fileNameAndFunctionKey.Split('#');
        var fileName = array[0];
        var functionKey = array[1];
        var path = string.Empty;
        var folderList = configuration.GetSection("FileServerDirectory").Value!.Split(",");
        foreach (var folder in folderList)
        {
            path = CommonHelper.GetFolder(functionKey, folder);
            if (!System.IO.File.Exists($"{path}{fileName}")) continue;
            break;

        }
        service.WriteUserLog(napSession.UserName, functionKey, Path.GetFileName(fileName));
        return GetFile(fileName, path);
    }

    private FileStreamResult GetMultiFiles(List<string> fileNames)
    {
        if (fileNames.Count == 0) return null;
        var zipFolderName = $"Auto-Generated Report - {napSession.UserName} - {DateTimeOffset.Now:yyyy-MM-dd hh-mm tt}";
        var rootFolder = CommonHelper.GetFolder(fileNames[0].Split('|')[1].Split('#')[1],
            configuration.GetSection("FileServerDirectory").Value!.Split(",")[0]);
        var zipFolder = Path.Combine(rootFolder, zipFolderName);
        if (!Directory.Exists(zipFolder))
        {
            Directory.CreateDirectory(zipFolder);
        }

        foreach (var file in fileNames)
        {
            var groupName = file.Split('|')[0];
            var fileNameAndFunctionKey = file.Split('|')[1];
            var array = fileNameAndFunctionKey.Split('#');
            var fileName = array[0];
            var functionKey = array[1];

            var newFolder = Path.Combine(zipFolder, groupName);
            if (!Directory.Exists(newFolder))
            {
                Directory.CreateDirectory(newFolder);
            }

            var folderList = configuration.GetSection("FileServerDirectory").Value!.Split(",");
            foreach (var folderItem in folderList)
            {
                var folder = CommonHelper.GetFolder(functionKey, folderItem);
                var fileUrl = $"{folder}{fileName}";
                if (!System.IO.File.Exists(fileUrl)) continue;
                var newFileUrl = $"{newFolder}/{Path.GetFileName(fileName)}";
                System.IO.File.Copy(fileUrl, newFileUrl);
                service.WriteUserLog(napSession.UserName, functionKey, Path.GetFileName(fileName));
                break;
            }

        }
        ZipFile.CreateFromDirectory(zipFolder, $"{zipFolder}.zip");
        var excelFiles = GetFile($"/{zipFolderName}.zip", rootFolder);
        autoGeneratedTodayReportService.DeleteDirectoryAndFile($"{zipFolder}.zip", zipFolder);
        return excelFiles;
    }

    private FileStreamResult GetFile(string fileName, string folder)
    {
        var filePath = $"{folder}{fileName}";
        var fileExtension = Path.GetExtension(filePath);
        var mimeType = GetMimeType(fileExtension);
        var shortFileName = Path.GetFileName(filePath);
        var fileStream = new FileStream(filePath, FileMode.Open, FileAccess.Read, FileShare.Read, 4096, FileOptions.Asynchronous);
        HttpContext.Response.Headers.Add("Access-Control-Expose-Headers", "Content-Disposition");
        return File(fileStream, mimeType, shortFileName);
    }

    private static string GetMimeType(string fileExtension)
    {
        if (fileExtension.StartsWith("."))
        {
            fileExtension = fileExtension[1..];
        }

        return fileExtension.ToLower() switch
        {
            "xls" => "application/vnd.ms-excel",
            "xlsx" => "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
            "doc" => "application/msword",
            "zip" => "application/x-zip-compressed",
            "pdf" => "application/pdf",
            _ => MediaTypeNames.Application.Octet
        };
    }
}