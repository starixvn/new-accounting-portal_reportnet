using AutoGeneratedReport.Services;

namespace Nap_Reports.Sites.DependencyInjection;

public static class AutoGeneratedReportInjection
{
    public static void RegisterAutoGeneratedReportServices(this IServiceCollection service)
    {
        service.AddTransient<AutoGeneratedReportService, AutoGeneratedReportServiceImp>();
        service.AddTransient<AutoGeneratedTodayReportService, AutoGeneratedTodayReportServiceImp>();
        service.AddTransient<AutoGeneratedHistoryReportService, AutoGeneratedHistoryReportServiceImp>();
    }
}