Namespace.Register("Fanex.AccountingReports.Misc.AutoGeneratedReport");
Fanex.AccountingReports.Misc.AutoGeneratedReport = function () {
    var self = this;
    self.reportsByUser = [];

    self.domElements = {
        rdTodayReport: null,
        rdHistoryReport: null,
        ddlReports: null,
        btnGenerate: null,
        reportContainer: null,
        reportContent: null
    };

    self.cacheDomElements = function () {
        self.domElements.rdTodayReport = $("#rdtodayreport");
        self.domElements.rdHistoryReport = $("#rdhistoryreport");
        self.domElements.ddlReports = $("#ddlreports");
        self.domElements.btnGenerate = $("#btnGenerate");
        self.domElements.reportContent = $('#autoGeneratedReportMainGrid');
    };

    self.InitPage = function () {
        self.cacheDomElements();
        self.bindingEvent();
        self.getReports();
    };

    self.bindingEvent = function () {
        self.domElements.btnGenerate.click(function () {
            var isChecked = self.domElements.rdTodayReport.is(':checked');
            if (isChecked) {
                self.getTodayReport();
            }
            else {
                self.getHistoryReport();
            }
        });

        self.domElements.rdTodayReport.change(function () {
            $("#report-items-container").addClass("display-none");
        });

        self.domElements.rdHistoryReport.change(function () {
            $("#report-items-container").removeClass("display-none");
        });
    };

    var hideReport = function () {
        $('#autoGeneratedReportGrid').addClass("display-none");
    };

    self.getTodayReport = function () {
        AccReport.disableInput();
        AccReport.utility.CallAjax(this,
                                    window.rootUrl + "/api/auto-generated-report/today-reports",
                                    self.reportsByUser,
                                    self.implementRenderFiles,
                                    AccReport.enableInput,
                                    AccReport.enableInput);
    };

    self.getHistoryReport = function () {
        var element = self.domElements.ddlReports.find('option:selected');
        var foldername = element.attr("foldername");
        var parentfunctionkey = element.attr("parentfunctionkey");
        var param = {
            FolderName: foldername,
            ParentFunctionKey: parentfunctionkey
        };
        AccReport.disableInput();
        AccReport.utility.CallAjax(this,
                                    window.rootUrl + "/api/auto-generated-report/history-reports",
                                    param,
                                    self.renderFilesGroupByDay,
                                    AccReport.enableInput,
                                    AccReport.enableInput);
    };

    self.getReports = function () {
        AccReport.disableInput();
        AccReport.utility.CallAjax(this,
                                    window.rootUrl + "/api/auto-generated-report/reports",
                                    null,
                                    self.renderReportList,
                                    AccReport.enableInput,
                                    AccReport.enableInput);
    };

    self.renderReportList = function (reports) {
        self.reportsByUser = reports;
        var options = [];
        for (var i = 0; i < reports.length; i++) {
            var folderName = reports[i].FunctionKey;
            var parentFunctionKey = reports[i].ParentFunctionKey;
            options.push("<option parentfunctionkey='" + parentFunctionKey + "' foldername='" + folderName + "'>" + reports[i].FunctionName + " </option>");
        }

        self.domElements.ddlReports.empty().html(options);
    }

    self.implementRenderFiles = function (rs) {
        var title = "<span title='Download All' onclick='downloadMultiFiles()' class='downloadAll'>&nbsp;&nbsp;</span> Click on the link as below to download report excel file";
        var checkBoxAllGroup = "<input title='Select All' type='checkbox' id='chkAll' onclick='eventOnAllGroup()'/>";
        var columns = [
					{ HeaderText: checkBoxAllGroup, Width: 20, Name: "GroupName", CellAlign: "center", HeaderAlign: "center" },
					{ HeaderText: "File Name", Width: 500, Name: "Name", CellAlign: "left", HeaderAlign: "center", ShowCollapseExpand: true },
                    { HeaderText: "Generated Date", Width: 100, Name: "GeneratedDate", CellAlign: "center", HeaderAlign: "center" }
        ];

        var bodyData = [];

        if (rs && rs.length > 0) {
            var reportLength = rs.length;
            var currentLeafRow = [];
            var currentChildRow = [];
            for (var rowIndex = 0; rowIndex < reportLength; rowIndex++) {
                var row = rs[rowIndex];
                var checkBoxGroup = "<input type = 'checkbox' id='chkGroup_" + rowIndex + "' class='checkBoxGroup' onclick='eventOnGroup(" + rowIndex + ")' />";
                var currentRow =
                {
                    Columns: [
                                { Name: "GroupName", Value: checkBoxGroup },
                                { Name: "Name", Value: row.GroupName, CellAlign: "left", MergeColNumber: 2 }
                    ],
                    SubRows: []
                };

                var leafLength = row.Reports.length;
                for (var j = 0; j < leafLength; j++) {
                    var id = rowIndex + "_" + j;
                    var leafRow = row.Reports[j];
                    var icon = self.getIcon(leafRow);

                    var checkBox = "<input type = 'checkbox' functionkey='" + leafRow.FunctionKey
                    + "' groupname='" + row.GroupName
                    + "' id='" + id
                    + "' class='chkSub_" + rowIndex + " chkGroupLeafByMonth_" + rowIndex
                    + "' foldername='" + leafRow.FolderName + "'/>";

                    var reportName = "<span id='report_" + id + "' class='hand' onclick=\"downloadSingleFile('" + id + "')\">" + icon + leafRow.Name + "</span>";
                    currentLeafRow =
                    {
                        Columns: [
                            { Name: "GroupName", Value: checkBox },
                            { Name: "Name", Value: reportName },
                            { Name: "GeneratedDate", Value: leafRow.GeneratedDate }
                        ]
                    };

                    currentRow.SubRows.push(currentLeafRow);
                }

                bodyData.push(currentRow);
            }
        }

        var gridOptions = {
            columns: columns,
            showFooter: true,
            showTitle: true,
            titleInfo: {
                text: title,
                showExcelButton: false,
                exportExcelFunction: function () { downloadMultiFiles(); },
                showCollapseExpandButton: true
            },
            bodyRows: bodyData,
            gridExpandHeight: 185 + AccReportData.Constants.ReportMarginBottom,
            showPager: false,
            showTree: true
        };

        self.domElements.reportContent.fanexGrid(gridOptions);
    };

    self.renderFilesGroupByDay = function (rs) {
        var isChecked = self.domElements.rdHistoryReport.is(':checked');
        var element = self.domElements.ddlReports.find('option:selected');
        var parentfunctionkey = element.attr("parentfunctionkey");
        if (isChecked && parentfunctionkey != 'Others') {
            self.implementRenderFiles(rs);
        }
        else {
            self.implementRenderFilesGroupByDay(rs);
        }
    };

    self.implementRenderFilesGroupByDay = function (rs) {
        var title = "<span title='Download All' onclick='downloadMultiFiles()' class='downloadAll'>&nbsp;&nbsp;</span> Click on the link as below to download report excel file";
        var checkBoxAllGroup = "<input title='Select All' type='checkbox' id='chkAll' onclick='eventOnAllGroup()'/>";
        var columns =
            [
                { HeaderText: checkBoxAllGroup, Width: 20, Name: "GroupName", CellAlign: "center", HeaderAlign: "center" },
                { HeaderText: "File Name", Width: 500, Name: "Name", CellAlign: "left", HeaderAlign: "center", ShowCollapseExpand: true },
                { HeaderText: "Generated Date", Width: 100, Name: "GeneratedDate", CellAlign: "center", HeaderAlign: "center" }
            ];

        var bodyData = [];

        if (rs && rs.length > 0) {
            var reportLength = rs.length;
            var currentLeafRow = [];
            var currentChildRow = [];
            for (var rowIndex = 0; rowIndex < reportLength; rowIndex++) {
                var row = rs[rowIndex];
                var checkBoxGroup = "<input type = 'checkbox' id='chkGroup_" + rowIndex + "' class='checkBoxGroup' onclick='eventOnGroup(" + rowIndex + ")' />";
                var currentRow =
                    {
                        Columns: [
                                    { Name: "GroupName", Value: checkBoxGroup },
                                    { Name: "Name", Value: row.GroupName, CellAlign: "left", MergeColNumber: 2 }
                        ],
                        SubRows: []
                    };

                var subRowLength = row.Rows.length;
                for (var subRowIndex = 0; subRowIndex < subRowLength; subRowIndex++) {
                    var subRow = row.Rows[subRowIndex];
                    var subId = rowIndex + "_" + subRowIndex;
                    var checkBoxSubGroup = "<input type = 'checkbox' id='chkSubGroup_" + subId + "' class='chkGroupLeafByMonth_" + rowIndex + "' onclick=\"eventOnSubGroup('" + subId + "')\" />";
                    var currentSubRow =
                        {
                            Columns: [
                                        { Name: "GroupName", Value: checkBoxSubGroup },
                                        { Name: "Name", Value: subRow.GroupName, CellAlign: "left", MergeColNumber: 2 }
                            ],
                            SubRows: []
                        };

                    var leafLength = subRow.Reports.length;
                    for (var j = 0; j < leafLength; j++) {
                        var id = subId + "_" + j;
                        var leafRow = subRow.Reports[j];
                        var icon = self.getIcon(leafRow);
                        var checkBox = "<input type = 'checkbox' functionkey='" + leafRow.FunctionKey
                            + "' groupname='" + row.GroupName
                            + "' id='" + id
                            + "' class='chkSub_" + rowIndex + " chkGroupLeafByDay_" + subId + " chkGroupLeafByMonth_" + rowIndex
                            + "' foldername='" + leafRow.FolderName + "'/>";

                        var reportName = "<span id='report_" + id + "' class='hand' onclick=\"downloadSingleFile('" + id + "')\">" + icon + leafRow.Name + "</span>";
                        currentLeafRow =
                            {
                                Columns: [
                                    { Name: "GroupName", Value: checkBox },
                                    { Name: "Name", Value: reportName },
                                    { Name: "GeneratedDate", Value: leafRow.GeneratedDate }
                                ]
                            };

                        currentSubRow.SubRows.push(currentLeafRow);
                    }

                    currentRow.SubRows.push(currentSubRow);
                }

                bodyData.push(currentRow);
            }
        }

        var gridOptions = {
            columns: columns,
            showFooter: true,
            showTitle: true,
            titleInfo: {
                text: title,
                showExcelButton: false,
                exportExcelFunction: function () { downloadMultiFiles(); },
                showCollapseExpandButton: true
            },
            bodyRows: bodyData,
            gridExpandHeight: 185 + AccReportData.Constants.ReportMarginBottom,
            showPager: false,
            showTree: true
        };

        self.domElements.reportContent.fanexGrid(gridOptions);

    };

    eventOnSubGroup = function (id) {
        var isChecked = $('#chkSubGroup_' + id).is(':checked');
        $('.chkGroupLeafByDay_' + id).prop('checked', isChecked);
    };

    eventOnGroup = function (id) {
        var isChecked = $('#chkGroup_' + id).is(':checked');
        $('.chkGroupLeafByMonth_' + id).prop('checked', isChecked);
    };

    eventOnAllGroup = function () {
        var isChecked = $('#chkAll').is(':checked');
        $('#tblContent_autoGeneratedReportMainGrid').find('input').prop('checked', isChecked);
    };

    downloadSingleFile = function (id) {
        var file = $('#' + id).attr('groupname') + "|" + $('#' + id).attr('foldername') + '#' + $('#' + id).attr('functionkey');
        var param = {
            FileName: file,
            IsMultiFiles: false
        };
        AccReport.disableInput();
        $('#iconDownloading').removeClass('display-none');
        AccReport.utility.CallAjaxForDownload(this,
            window.rootUrl + "/api/auto-generated-report/download",
            param,
            self.downloadFile,
            self.errorDownloadFile,
            self.completeDownloadFile);

        AccReport.enableInput();
    };

    downloadMultiFiles = function () {
        var files = [];
        $("input[class^='chkSub']").each(function () {
            var isChecked = $(this).is(':checked');
            if (isChecked) {
                var file = $(this).attr('groupname') + "|" + $(this).attr('foldername') + '#' + $(this).attr('functionkey');
                files.push(file);
            }
        });

        var param = {
            FileName: files.join('^'),
            IsMultiFiles: true
        };
        if (files.length == 0) {
            return;
        }

        AccReport.disableInput();
        $('#iconDownloading').removeClass('display-none');
        AccReport.utility.CallAjaxForDownload(this,
            window.rootUrl + "/api/auto-generated-report/download",
            param,
            self.downloadFile,
            self.errorDownloadFile,
            self.completeDownloadFile);
        AccReport.enableInput();
    };

    self.downloadFile = function (rs, fileName) {
        element = document.createElement('a');
        element.href = window.URL.createObjectURL(rs);
        element.download = fileName;
        element.style.display = 'none';
        document.body.appendChild(element);
        element.click();
        element.remove();
    };

    self.completeDownloadFile = function () {
        $('#iconDownloading').addClass('display-none');
    };

    self.errorDownloadFile = function () {
        $('#iconDownloading').addClass('display-none');
        AccReport.popUp.show("The file generation process encountered an error and cannot be completed. Please try again after a few minutes. !!!");
    };

    self.getIcon = function (leafRow) {
        var indexZip = leafRow.Name.indexOf('.zip');
        var iconExcel = '<span class="btnExcel">&nbsp;&nbsp;</span>';
        var iconZip = '<span class="btnZip">&nbsp;&nbsp;</span>';

        if (indexZip > -1) {
            return iconZip;
        }
        else {
            return iconExcel;
        }
    };
};

var autoGeneratedReport;

$(document).ready(function () {
    autoGeneratedReport = new Fanex.AccountingReports.Misc.AutoGeneratedReport();
    autoGeneratedReport.InitPage();
});